/**
 * Specific draft property IDs permitted to be previewed in the AI Studio preview/dev environment.
 * In production deployments, draft properties remain strictly hidden.
 */
const PREVIEW_APPROVED_DRAFT_IDS = new Set<string>([
  'anw-qurtubah-rent',
]);

const isAiStudioPreviewEnvironment = (): boolean => {
  if (typeof window === 'undefined') return false;
  const host = window.location.hostname;
  return (
    import.meta.env.DEV ||
    host.includes('run.app') ||
    host.includes('localhost') ||
    host.includes('127.0.0.1')
  );
};

/**
 * Returns true if a property is published and should be visible publicly.
 * In AI Studio preview environment, allows designated draft properties to be reviewed.
 */
export const isPropertyPublished = (property: Property): boolean => {
  if (isAiStudioPreviewEnvironment() && PREVIEW_APPROVED_DRAFT_IDS.has(property.id)) {
    return true;
  }

  if (property.status === 'draft' || property.isPublished === false) {
    return false;
  }
  return true;
};

/**
 * Publicly published properties (excludes drafts).
 */
export const publishedProperties: Property[] = propertiesData.filter(isPropertyPublished);

/**
 * Properties currently in draft status awaiting review and reorganization.
 */
export const draftProperties: Property[] = propertiesData.filter((p) => !isPropertyPublished(p));
