/**
 * Returns true if a property is confirmed, published, and authorized for public visibility.
 * Strictly requires property.status === 'published' AND property.isPublished === true.
 * Draft, demo, or unapproved properties are never published.
 */
export const isPropertyPublished = (property: Property): boolean => {
  if (property.status === 'draft' || property.isPublished === false) {
    return false;
  }
  return property.status === 'published' && property.isPublished === true;
};

/**
 * Publicly published properties (strictly confirmed and authorized).
 */
export const publishedProperties: Property[] = propertiesData.filter(isPropertyPublished);

/**
 * Properties currently in draft status awaiting review and client authorization.
 */
export const draftProperties: Property[] = propertiesData.filter((p) => !isPropertyPublished(p));
